'@ -split "`n"

$colorIndex = 0
foreach ($line in $asciiArt) {
    $coloredLine = ""
    $colorIndex++
    foreach ($char in $line.ToCharArray()) {
        $color = $colors[$colorIndex % $colors.Count]
        $coloredLine += "${ESC}[${color}m$char"
        $colorIndex++
    }
    $coloredLine += "${ESC}[0m"
    Write-Host $coloredLine
}
