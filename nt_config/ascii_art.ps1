$ESC = [char]27
$palettes = @{
    # 16-color palettes
    "Rainbow"   = 91,93,92,96,94,95        # Classic bright rainbow
    "Sunset"    = 91,93,95,53,55,97        # Red -> Yellow -> Pink -> Purple
    "Ocean"     = 94,96,36,39,45,51         # Blue -> Cyan gradient
    "Forest"    = 92,106,28,22,58,64       # Green gradient
    "Voltron"   = 91,93,92,96,94,95,97    # Bright pop-art style
}

# Select a palette (change this value to try different ones)
$colors = $palettes["Rainbow"]

$asciiArt = @'
